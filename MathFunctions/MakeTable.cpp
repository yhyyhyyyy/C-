#include <cmath>
#include <fstream>
#include <iomanip>
#include <iostream>

int main(int argc, char* argv[])
{
    if (argc != 2) return 1;
    std::ofstream output(argv[1]);
    if (!output) { std::cerr << "Cannot create table\n"; return 1; }
    output << "// Generated by MakeTable. Do not edit.\n#pragma once\n"
           << "static const double sqrtTable[] = {\n" << std::setprecision(17);
    for (int i = 0; i < 10; ++i) output << std::sqrt(static_cast<double>(i)) << ",\n";
    output << "};\n";
    output.close();
    return output ? 0 : 1;
}
